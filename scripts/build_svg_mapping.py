#!/usr/bin/env python3
"""Build the canonical SVG→concept mapping JSON (committed, reproducible).

Walks the 123 skola concept SVGs, resolves each to a Lärbild concept via
:mod:`app.svg_baseline` (the pure mapping layer), and writes a deterministic
``data/svg_baseline/mapping.json`` capturing, per SVG: its id, subject, the
resolved begrepp + area (or ``null`` = unmapped/gap), the match method, and the
SVG heading. Also emits a ``gap`` section: the larbild fysik/teknik concepts that
do NOT yet have an SVG baseline (the SVG-authoring lane's worklist), counted by
area.

Deterministic: same inputs → byte-identical output (sorted keys, sorted lists),
so committing it and re-running in CI is a clean diff. Pure read — writes only the
mapping JSON, touches no DB or storage.

Usage:
    python3 scripts/build_svg_mapping.py \
        [--svg-root /path/to/concept-images] \
        [--fysik-json /tmp/larbild-begrepp/fysik.json] \
        [--out data/svg_baseline/mapping.json]
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

# Allow running from the repo root without installing the package.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app import svg_baseline as sb  # noqa: E402
from app import taxonomy  # noqa: E402

DEFAULT_SVG_ROOT = "/home/claudecode/gt/skola/mayor/rig/frontend/public/concept-images"


def _norm_set(names) -> set[str]:
    return {sb.normalize(n) for n in names}


def build(svg_root: str, fysik_json: str | None) -> dict:
    concepts = sb.load_fysik_concepts(fysik_json)
    index = sb._build_index(concepts)

    items: list[dict] = []
    # Track which (subject, area, normalized-begrepp) got an SVG baseline.
    covered: set[tuple[str, str, str]] = set()

    for subdir, name, path in sb.iter_svgs(svg_root):
        key = f"{subdir}/{name}"
        heading = sb.svg_heading(path)
        if subdir in sb.FYSIK_SUBDIRS:
            subject = "fysik"
            concept = sb.resolve_fysik(subdir, name, heading, concepts, _index=index)
            if concept:
                begrepp = concept["begrepp"]
                area = concept["area"]
                method = "alias" if key in sb.FYSIK_ALIAS else "fuzzy"
                covered.add((subject, area, sb.normalize(begrepp)))
            else:
                begrepp = area = None
                method = "unmapped"
        elif subdir in sb.TEKNIK_SUBDIRS:
            subject = "teknik"
            begrepp, area = sb.TEKNIK_CONCEPTS[key]
            method = "teknik-created"
            covered.add((subject, area, sb.normalize(begrepp)))
        else:  # pragma: no cover - no other subdirs exist
            continue

        items.append({
            "svg": key,
            "subdir": subdir,
            "subject": subject,
            "begrepp": begrepp,
            "area": area,
            "method": method,
            "heading": heading,
        })

    items.sort(key=lambda d: d["svg"])

    # ── GAP analysis ────────────────────────────────────────────────────────
    # fysik: every larbild fysik concept whose normalized begrepp is NOT covered.
    fysik_by_area: dict[str, list[str]] = {}
    for c in concepts:
        fysik_by_area.setdefault(c["area"], []).append(c["begrepp"])
    fysik_gap: dict[str, list[str]] = {}
    fysik_have: dict[str, int] = {}
    for area, names in fysik_by_area.items():
        gap = sorted(
            {n for n in names if ("fysik", area, sb.normalize(n)) not in covered}
        )
        have = len(names) - len(gap)
        fysik_gap[area] = gap
        fysik_have[area] = have

    # teknik: the created concepts ARE the coverage; the gap is every taxonomy
    # teknik area's central-content topics not yet given an SVG. We surface the
    # per-area count of created concepts vs the area existing at all (teknik has
    # no begrepp dump, so "gap" = areas/topics with no SVG yet).
    teknik_have: dict[str, int] = {}
    for key, (begrepp, area) in sb.TEKNIK_CONCEPTS.items():
        teknik_have[area] = teknik_have.get(area, 0) + 1
    teknik_areas = {a["slug"]: a["name"] for a in taxonomy.subject("teknik")["areas"]}
    teknik_gap_areas = sorted(set(teknik_areas) - set(teknik_have))

    mapped = [i for i in items if i["begrepp"]]
    unmapped = [i for i in items if not i["begrepp"]]

    return {
        "_about": (
            "Canonical mapping of the 123 Claude-authored skola concept SVGs to "
            "Lärbild concepts. Generated by scripts/build_svg_mapping.py — do not "
            "hand-edit; change app/svg_baseline.py (alias/teknik tables) and "
            "regenerate. The matched concept's 'area' is authoritative for the "
            "Bibliotek node; an SVG with begrepp=null is the GAP (no clear concept)."
        ),
        "totals": {
            "svgs": len(items),
            "fysik_svgs": sum(1 for i in items if i["subject"] == "fysik"),
            "teknik_svgs": sum(1 for i in items if i["subject"] == "teknik"),
            "mapped": len(mapped),
            "unmapped": len(unmapped),
        },
        "items": items,
        "gap": {
            "fysik": {
                "total_concepts": len(concepts),
                "with_svg": sum(fysik_have.values()),
                "without_svg": sum(len(v) for v in fysik_gap.values()),
                "by_area_counts": {
                    a: {"with_svg": fysik_have[a], "without_svg": len(fysik_gap[a])}
                    for a in sorted(fysik_gap)
                },
                "missing_by_area": {a: fysik_gap[a] for a in sorted(fysik_gap) if fysik_gap[a]},
            },
            "teknik": {
                "note": (
                    "Teknik has no shipped begrepp dataset; the 25 SVGs each create "
                    "a concept row. 'with_svg_by_area' counts created concepts; "
                    "'areas_without_svg' are taxonomy teknik areas with no SVG yet."
                ),
                "created_concepts": len(sb.TEKNIK_CONCEPTS),
                "with_svg_by_area": {a: teknik_have[a] for a in sorted(teknik_have)},
                "areas_without_svg": [
                    {"area": a, "name": teknik_areas[a]} for a in teknik_gap_areas
                ],
            },
        },
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--svg-root", default=DEFAULT_SVG_ROOT)
    ap.add_argument("--fysik-json", default=None)
    ap.add_argument(
        # Committed alongside the mapping module (NOT under /data/, which is
        # gitignored for the runtime SQLite DB). This is reference data: the
        # canonical, reproducible SVG→concept mapping + gap analysis.
        "--out",
        default=str(Path(__file__).resolve().parent.parent
                    / "app" / "svg_baseline_mapping.json"),
    )
    args = ap.parse_args()

    mapping = build(args.svg_root, args.fysik_json)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        json.dumps(mapping, ensure_ascii=False, indent=2, sort_keys=False) + "\n",
        encoding="utf-8",
    )
    t = mapping["totals"]
    print(f"wrote {out}")
    print(f"  SVGs={t['svgs']} fysik={t['fysik_svgs']} teknik={t['teknik_svgs']} "
          f"mapped={t['mapped']} unmapped={t['unmapped']}")
    g = mapping["gap"]["fysik"]
    print(f"  fysik concepts={g['total_concepts']} with_svg={g['with_svg']} "
          f"without_svg={g['without_svg']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
